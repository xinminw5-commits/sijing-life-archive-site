// Explicit publishing allowlist: theory only. Never crawl cases, contacts, or the graph.
// Generated catalog is a deployable derivative; Markdown remains authoritative.
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const source = resolve(root, "../人生命格/outputs/读书工程/04_判断规则库");
const sections = ["白话解释", "使用条件", "失效条件", "反例与风险", "可推翻与降权条件"];
const rows = [];
for (const [folder, prefix, count, book] of [["格局派", "ZP", 35, "子平真诠"], ["调候派", "QT", 5, "穷通宝鉴"], ["旺衰派", "DT", 3, "滴天髓"]]) {
  const files = await readdir(resolve(source, folder));
  for (let n = 1; n <= count; n++) {
    const id = prefix + String(n).padStart(3, "0");
    const matches = files.filter(f => f.startsWith(id + "_") && f.endsWith(".md"));
    if (matches.length !== 1) throw new Error(`Ambiguous source ${id}`);
    const text = await readFile(resolve(source, folder, matches[0]), "utf8");
    if (!text.includes("生命周期状态：正式")) throw new Error(`Non-formal source ${id}`);
    const extracts = Object.fromEntries(sections.map(section => {
      const headings = section === "失效条件" ? ["失效条件", "失效与重定条件", "失效与降级条件"] : section === "可推翻与降权条件" ? ["可推翻与降权条件", "互证取舍与可推翻条件", "冲突证据"] : [section];
      const match = headings.map(heading => text.match(new RegExp(`^## ${heading}\\s*\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, "m"))).find(Boolean);
      if (!match?.[1].trim()) throw new Error(`Missing section ${id}/${section}`);
      // Do not publish local paths or copy original book quotations.
      const cleaned = match[1].trim().replace(/`人生命格\/[^`]+`/g, "相关规则专题");
      if (/CASE-\d|@|身份证|联系方式/.test(cleaned)) throw new Error(`Private data in ${id}`);
      return [section, cleaned];
    }));
    rows.push({ id, title: text.split("\n")[0].replace(/^# \w+\s+/, ""), book, status: "formal", realityValidation: "unvalidated", sourceDigest: createHash("sha256").update(text).digest("hex"), ...extracts });
  }
}
await mkdir(resolve(root, "server/knowledge"), { recursive: true });
await writeFile(resolve(root, "server/knowledge/rule-catalog.generated.ts"), "// Generated by scripts/sync-rule-catalog.mjs. Theory only; do not edit.\nexport const ruleCatalog = " + JSON.stringify(rows, null, 2) + " as const;\n");
console.log(`Synced ${rows.length} formal rules; no private cases included.`);
